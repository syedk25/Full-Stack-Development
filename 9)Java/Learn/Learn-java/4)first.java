
// This program prints a welcome message to the console.

class first {
    public static void main(String[] args) {
        System.out.println("welcome to java programming");
    }
}

/*

Keywords:
- class: blueprint for objects, used to declare a class
- public: accessible from anywhere
- static: belongs to the class, not an instance,JVM calls the main method directly using the class name.
          No object creation needed.
- void: no return value
- main: program entry point
-String[] args : for command line arguments
- String: text data type
*/






